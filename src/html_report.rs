//! Standalone HTML report generation.
//!
//! Renders a [`QcReport`] into one self-contained HTML file (embedded CSS,
//! inline SVG, and a few lines of optional vanilla JavaScript for column
//! sorting; no external assets). Layout:
//!
//! * a summary panel: completeness/contamination gauges when the input is a
//!   single genome or contig; for many genomes/contigs, the quality-tier
//!   distribution of the primary validator with median estimates;
//! * assembly statistics for the whole input;
//! * a results table with one row per genome (bacteria / archaea /
//!   eukaryote) or per contig (virus / mixed), capped at [`MAX_TABLE_ROWS`];
//! * detailed per-validator cards for small inputs;
//! * warnings, each tagged with its validator and genome/contig.

use crate::common::{Domain, QcRecord, QcReport, Quality};
use std::collections::HashMap;

/// Rows shown in the results table (the TSV/JSON always hold everything).
pub const MAX_TABLE_ROWS: usize = 5000;
/// Detailed cards are rendered when there are at most this many genomes/contigs.
const MAX_DETAIL_UNITS: usize = 8;
/// Warnings listed in the report.
const MAX_WARNINGS: usize = 300;

/// Validators whose records describe a whole genome (one record per genome).
const GENOME_VALIDATORS: &[&str] = &["checkm2", "busco", "eukcc", "sage"];

/// Assembly statistics of one input genome: `(genome name, key/value table)`.
pub type GenomeStats = (String, Vec<(String, String)>);

/// Render the whole report to an HTML document string.
///
/// `totals` are statistics over the whole input (size, N50, GC, coding
/// density, ORF count, …); `per_genome` are the same statistics per input
/// genome for genome-level runs (empty for per-contig runs).
pub fn render(
    report: &QcReport,
    input_name: &str,
    domain: Domain,
    totals: &[(String, String)],
    per_genome: &[GenomeStats],
) -> String {
    let per_contig = matches!(domain, Domain::Virus | Domain::Mixed);
    let units = Units::collect(report, per_contig, per_genome);
    let primary = primary_validator(report, per_contig);

    let mut body = String::new();
    if units.names.is_empty() {
        body.push_str(
            "<section class=\"hero\"><div class=\"empty\">No validator produced a result \
             (were the reference databases found? see <code>sentinel-x doctor</code>).</div></section>\n",
        );
    } else if units.names.len() == 1 {
        let u = units.view(0);
        body.push_str(&render_hero_single(&u, primary, per_contig));
    } else {
        body.push_str(&render_overview(&units, primary, per_contig));
    }

    body.push_str(&render_stat_strip(totals, units.names.len(), per_contig, report));

    // marker breakdown for a single eukaryote / BUSCO genome
    if units.names.len() == 1 {
        let u = units.view(0);
        if let Some(rec) = u.rec("eukcc").or_else(|| u.rec("busco")) {
            body.push_str(&render_marker_panel(rec));
        }
    }

    if !units.names.is_empty() {
        body.push_str(&render_table(&units, per_contig));
        body.push_str(&render_cards(&units, per_contig));
    }
    body.push_str(&render_warnings(report, &units));

    let genome = html_escape(input_name);
    format!(
        "<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n\
         <title>Sentinel-X QC — {genome}</title>\n<style>{css}</style>\n</head>\n\
         <body>\n<div class=\"wrap\">\n\
         <header class=\"hd\">\n\
           <div class=\"brand\"><span class=\"logo\">◇</span> Sentinel-X</div>\n\
           <div class=\"sub\">{domain_label} genome quality report · {date} · v{version}</div>\n\
         </header>\n\
         <div class=\"genome\">{genome}</div>\n\
         {body}\n\
         <footer class=\"ft\">Generated by Sentinel-X {version} · the TSV/JSON outputs hold every field</footer>\n\
         </div>\n<script>{js}</script>\n</body>\n</html>\n",
        genome = genome,
        css = CSS,
        js = SORT_JS,
        domain_label = domain_name(domain),
        date = current_date(),
        version = crate::common::VERSION,
        body = body,
    )
}

// ------------------------------------------------------------------ units

/// The report grouped by genome (genome-level runs) or contig (per-contig runs).
struct Units<'a> {
    names: Vec<String>,
    records: HashMap<String, Vec<&'a QcRecord>>,
    stats: HashMap<String, &'a Vec<(String, String)>>,
    kind: &'static str,
}

/// One genome or contig with its records.
struct UnitView<'a> {
    name: &'a str,
    records: &'a [&'a QcRecord],
    stats: Option<&'a Vec<(String, String)>>,
}

impl<'a> Units<'a> {
    fn collect(report: &'a QcReport, per_contig: bool, per_genome: &'a [GenomeStats]) -> Units<'a> {
        let mut names: Vec<String> = Vec::new();
        let mut records: HashMap<String, Vec<&QcRecord>> = HashMap::new();
        for r in &report.records {
            let unit = if per_contig || GENOME_VALIDATORS.contains(&r.validator.as_str()) {
                Some(r.contig_id.clone())
            } else {
                extra(r, "genome")
            };
            let Some(unit) = unit else { continue };
            let e = records.entry(unit.clone()).or_default();
            if e.is_empty() {
                names.push(unit);
            }
            e.push(r);
        }
        let mut stats = HashMap::new();
        if !per_contig {
            for (name, table) in per_genome {
                stats.insert(name.clone(), table);
            }
        }
        Units { names, records, stats, kind: if per_contig { "contig" } else { "genome" } }
    }

    fn view(&self, i: usize) -> UnitView<'_> {
        let name = &self.names[i];
        UnitView {
            name,
            records: self.records.get(name).map(|v| v.as_slice()).unwrap_or(&[]),
            stats: self.stats.get(name).copied(),
        }
    }

    fn any(&self, validator: &str) -> bool {
        self.records.values().any(|rs| rs.iter().any(|r| r.validator == validator))
    }
}

impl<'a> UnitView<'a> {
    fn rec(&self, validator: &str) -> Option<&'a QcRecord> {
        self.records.iter().copied().find(|r| r.validator == validator)
    }

    fn all(&self, validator: &'a str) -> impl Iterator<Item = &'a QcRecord> + 'a {
        self.records.iter().copied().filter(move |r| r.validator == validator)
    }

    fn stat(&self, key: &str) -> Option<String> {
        self.stats.and_then(|t| t.iter().find(|(k, _)| k == key).map(|(_, v)| v.clone()))
    }

    fn length(&self) -> usize {
        self.stat("genome_size")
            .and_then(|v| v.parse().ok())
            .or_else(|| self.records.iter().find(|r| GENOME_VALIDATORS.contains(&r.validator.as_str())).map(|r| r.length))
            .or_else(|| self.records.first().map(|r| r.length))
            .unwrap_or(0)
    }

    fn warnings(&self) -> Vec<String> {
        self.records.iter().flat_map(|r| r.warnings.iter().map(move |w| format!("{}: {}", r.validator, w))).collect()
    }
}

/// The validator whose verdict summarises a unit.
fn primary_validator(report: &QcReport, per_contig: bool) -> Option<&'static str> {
    let wanted: &[&'static str] = if per_contig { &["checkv"] } else { &["eukcc", "checkm2", "busco"] };
    wanted.iter().copied().find(|v| report.records.iter().any(|r| r.validator == *v))
}

// ------------------------------------------------------------------ summary

fn render_hero_single(u: &UnitView, primary: Option<&str>, per_contig: bool) -> String {
    let rec = primary.and_then(|p| u.rec(p));
    let (comp, cont, quality, validator) = match rec {
        Some(r) => (r.completeness, r.contamination, r.quality, validator_title(&r.validator)),
        None => (None, None, Quality::NotDetermined, "no estimator".to_string()),
    };
    let mut notes: Vec<String> = Vec::new();
    if per_contig {
        if let Some(t) = u.rec("trace") {
            notes.push(format!("TRACE: {}", trace_label(t)));
        }
    } else if let Some(s) = u.rec("sage") {
        if let Some(v) = extra(s, "discordant_bp_pct") {
            notes.push(format!("SAGE: {v}% of sequence off the core composition"));
        }
    }
    let comp_gauge = gauge(comp.unwrap_or(0.0), "Completeness", comp.is_some(), false);
    let cont_gauge = gauge(cont.unwrap_or(0.0), "Contamination", cont.is_some(), true);
    let (badge_class, badge_text) = quality_badge(quality);
    let notes_html: String = notes.iter().map(|n| format!("<div class=\"qsrc\">{}</div>", html_escape(n))).collect();
    format!(
        "<section class=\"hero\">\n{comp_gauge}\n{cont_gauge}\n\
         <div class=\"herobadge\">\n\
           <div class=\"qbadge {badge_class}\">{badge_text}</div>\n\
           <div class=\"qsrc\">assessed by <b>{validator}</b></div>\n{notes_html}\n\
         </div>\n</section>\n",
        validator = html_escape(&validator),
    )
}

fn render_overview(units: &Units, primary: Option<&str>, per_contig: bool) -> String {
    let n = units.names.len();
    let kind = if n == 1 { units.kind.to_string() } else { format!("{}s", units.kind) };
    let mut main = String::new();
    match primary {
        Some(p) => {
            let mut counts = [0usize; 5];
            let (mut comps, mut conts) = (Vec::new(), Vec::new());
            let mut assessed = 0usize;
            for i in 0..n {
                let u = units.view(i);
                if let Some(r) = u.rec(p) {
                    assessed += 1;
                    counts[tier_index(r.quality)] += 1;
                    if let Some(c) = r.completeness {
                        comps.push(c);
                    }
                    if let Some(c) = r.contamination {
                        conts.push(c);
                    }
                }
            }
            let segs: Vec<(&str, usize, &str)> = vec![
                ("Complete", counts[0], "t-cp"),
                ("High-quality", counts[1], "t-hi"),
                ("Medium-quality", counts[2], "t-md"),
                ("Low-quality", counts[3], "t-lo"),
                ("Not-determined", counts[4], "t-nd"),
            ];
            let mut foot = Vec::new();
            if let Some(m) = median(&mut comps) {
                foot.push(format!("median completeness {m:.2}% (n={})", comps.len()));
            }
            if let Some(m) = median(&mut conts) {
                foot.push(format!("median contamination {m:.2}% (n={})", conts.len()));
            }
            if assessed < n {
                foot.push(format!("{} {} without a {} result", n - assessed, kind, validator_title(p)));
            }
            main.push_str(&dist_bar(&format!("{} quality", validator_title(p)), &segs, &foot.join(" · ")));
        }
        None if per_contig && units.any("trace") => {
            let mut counts = [0usize; 4];
            for i in 0..n {
                if let Some(t) = units.view(i).rec("trace") {
                    let k = match extra(t, "trace_confidence").as_deref() {
                        Some("complete") => 0,
                        Some("highly-complete") => 1,
                        Some("partial") => 2,
                        _ => 3,
                    };
                    counts[k] += 1;
                }
            }
            let segs: Vec<(&str, usize, &str)> = vec![
                ("complete", counts[0], "t-cp"),
                ("highly-complete", counts[1], "t-hi"),
                ("partial", counts[2], "t-md"),
                ("fragment", counts[3], "t-lo"),
            ];
            main.push_str(&dist_bar(
                "TRACE confidence (database-free)",
                &segs,
                "no CheckV database: completeness and contamination were not estimated",
            ));
        }
        None => {
            main.push_str(
                "<div class=\"ovtitle\">No completeness estimator ran</div>\
                           <div class=\"ovfoot\">install a reference database (see <code>sentinel-x doctor</code>)</div>",
            );
        }
    }
    format!(
        "<section class=\"hero overview\">\n\
         <div class=\"ovcount\"><div class=\"ovnum\">{n}</div><div class=\"ovlab\">{kind}</div></div>\n\
         <div class=\"ovmain\">{main}</div>\n</section>\n",
        kind = html_escape(&kind),
    )
}

/// Stacked distribution bar with a legend.
fn dist_bar(title: &str, segs: &[(&str, usize, &str)], foot: &str) -> String {
    let total: usize = segs.iter().map(|s| s.1).sum();
    let mut bar = String::new();
    let mut legend = String::new();
    for (label, count, class) in segs {
        if total > 0 && *count > 0 {
            bar.push_str(&format!(
                "<div class=\"seg {class}\" style=\"width:{:.3}%\" title=\"{}: {count}\"></div>",
                100.0 * *count as f64 / total as f64,
                html_escape(label)
            ));
        }
        legend.push_str(&format!("<span><i class=\"dot {class}\"></i>{} <b>{count}</b></span>", html_escape(label)));
    }
    format!(
        "<div class=\"ovtitle\">{}</div><div class=\"mbar\">{bar}</div><div class=\"mlegend\">{legend}</div>\
         <div class=\"ovfoot\">{}</div>",
        html_escape(title),
        html_escape(foot)
    )
}

fn tier_index(q: Quality) -> usize {
    match q {
        Quality::Complete => 0,
        Quality::High => 1,
        Quality::Medium => 2,
        Quality::Low => 3,
        Quality::NotDetermined => 4,
    }
}

fn median(v: &mut [f64]) -> Option<f64> {
    if v.is_empty() {
        return None;
    }
    v.sort_by(|a, b| a.total_cmp(b));
    let n = v.len();
    Some(if n % 2 == 1 { v[n / 2] } else { (v[n / 2 - 1] + v[n / 2]) / 2.0 })
}

/// A circular SVG gauge. `danger` flips the colour ramp (low is good).
fn gauge(pct: f64, label: &str, has_value: bool, danger: bool) -> String {
    let p = pct.clamp(0.0, 100.0);
    let r = 54.0;
    let circ = 2.0 * std::f64::consts::PI * r;
    let dash = circ * p / 100.0;
    let gap = circ - dash;
    let color = if !has_value {
        "#4b5563"
    } else if danger {
        if p < 5.0 {
            "#34d399"
        } else if p < 10.0 {
            "#fbbf24"
        } else {
            "#f87171"
        }
    } else if p >= 90.0 {
        "#34d399"
    } else if p >= 50.0 {
        "#fbbf24"
    } else {
        "#f87171"
    };
    let value = if has_value { format!("{p:.1}<tspan class=\"pct\">%</tspan>") } else { "n/a".to_string() };
    format!(
        "<div class=\"gauge\">\n\
         <svg viewBox=\"0 0 140 140\" width=\"150\" height=\"150\" role=\"img\" aria-label=\"{label} {aria}\">\n\
           <circle cx=\"70\" cy=\"70\" r=\"{r}\" fill=\"none\" stroke=\"#20293a\" stroke-width=\"12\"/>\n\
           <circle cx=\"70\" cy=\"70\" r=\"{r}\" fill=\"none\" stroke=\"{color}\" stroke-width=\"12\"\n\
             stroke-linecap=\"round\" stroke-dasharray=\"{dash:.2} {gap:.2}\" transform=\"rotate(-90 70 70)\"/>\n\
           <text x=\"70\" y=\"76\" text-anchor=\"middle\" class=\"gval\">{value}</text>\n\
         </svg>\n\
         <div class=\"glabel\">{label}</div>\n\
         </div>\n",
        aria = if has_value { format!("{p:.1}%") } else { "not available".into() },
        label = html_escape(label),
    )
}

/// Key numbers for the whole input.
fn render_stat_strip(totals: &[(String, String)], n_units: usize, per_contig: bool, report: &QcReport) -> String {
    let gs = |key: &str| -> Option<String> { totals.iter().find(|(k, _)| k == key).map(|(_, v)| v.clone()) };
    let mut cells: Vec<(String, String)> = Vec::new();
    if !per_contig && n_units > 1 {
        cells.push(("Genomes".into(), n_units.to_string()));
    }
    if let Some(v) = gs("total_coding_sequences") {
        cells.push(("ORFs / genes".into(), v));
    }
    if let Some(v) = gs("genome_size") {
        let label = if n_units > 1 || per_contig { "Total length" } else { "Genome size" };
        cells.push((label.into(), format_bp(&v)));
    }
    if let Some(v) = gs("num_contigs") {
        cells.push(("Contigs".into(), v));
    }
    if let Some(v) = gs("contig_n50") {
        cells.push(("Contig N50".into(), format_bp(&v)));
    }
    if let Some(v) = gs("max_contig_length") {
        cells.push(("Longest contig".into(), format_bp(&v)));
    }
    if let Some(v) = gs("gc_percent").or_else(|| gs("gc_content")) {
        cells.push(("GC content".into(), format!("{v}%")));
    }
    if let Some(v) = gs("coding_density") {
        cells.push(("Coding density".into(), format_fraction_pct(&v)));
    }
    if let Some(v) = gs("average_gene_length_aa") {
        cells.push(("Avg protein (aa)".into(), v));
    }
    if cells.is_empty() {
        cells.push(("Records".into(), report.records.len().to_string()));
    }
    let mut s = String::from("<section class=\"stripwrap\"><div class=\"strip\">\n");
    for (label, value) in cells {
        s.push_str(&format!(
            "<div class=\"stat\"><div class=\"snum\">{}</div><div class=\"slabel\">{}</div></div>\n",
            html_escape(&value),
            html_escape(&label)
        ));
    }
    s.push_str("</div></section>\n");
    s
}

/// Stacked bar of single-copy / duplicated / missing markers (EukCC, BUSCO).
fn render_marker_panel(rec: &QcRecord) -> String {
    let num = |k: &str| extra(rec, k).and_then(|v| v.parse::<f64>().ok());
    let (ex, found, dup, frag, set) = if rec.validator == "busco" {
        let single = num("single");
        let dup = num("duplicated");
        let (Some(n), Some(s), Some(d)) = (num("n"), single, dup) else { return String::new() };
        (n, s + d, d, num("fragmented").unwrap_or(0.0), rec.method.clone())
    } else {
        let (Some(e), Some(f), Some(d)) = (num("markers_expected"), num("markers_found"), num("markers_multicopy")) else {
            return String::new();
        };
        (e, f, d, 0.0, rec.method.clone())
    };
    if ex <= 0.0 {
        return String::new();
    }
    let single = (found - dup).max(0.0);
    let missing = (ex - found - frag).max(0.0);
    let w = |n: f64| format!("{:.2}%", 100.0 * n / ex);
    let frag_html = if frag > 0.0 {
        format!("<div class=\"seg frag\" style=\"width:{}\" title=\"fragmented: {frag:.0}\"></div>", w(frag))
    } else {
        String::new()
    };
    let frag_legend = if rec.validator == "busco" {
        format!("<span><i class=\"dot frag\"></i>Fragmented {frag:.0}</span>")
    } else {
        String::new()
    };
    format!(
        "<section class=\"markerpanel\">\n\
         <div class=\"mtitle\">{title} <span class=\"mset\">{set}</span></div>\n\
         <div class=\"mbar\">\
           <div class=\"seg single\" style=\"width:{ws}\" title=\"single-copy: {single:.0}\"></div>\
           <div class=\"seg dup\" style=\"width:{wd}\" title=\"multi-copy: {dup:.0}\"></div>{frag_html}\
           <div class=\"seg miss\" style=\"width:{wm}\" title=\"missing: {missing:.0}\"></div>\
         </div>\n\
         <div class=\"mlegend\">\
           <span><i class=\"dot single\"></i>Single-copy {single:.0}</span>\
           <span><i class=\"dot dup\"></i>{duplabel} {dup:.0}</span>{frag_legend}\
           <span><i class=\"dot miss\"></i>Missing {missing:.0}</span>\
           <span class=\"mtot\">of {ex:.0} expected</span>\
         </div>\n</section>\n",
        title = if rec.validator == "busco" { "BUSCO markers" } else { "EukCC markers" },
        duplabel = if rec.validator == "busco" { "Duplicated" } else { "Multi-copy" },
        set = html_escape(&set),
        ws = w(single),
        wd = w(dup),
        wm = w(missing),
    )
}

