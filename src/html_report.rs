/// Compact method label for the table (full text on hover).
fn method_cell(m: &str) -> Cell {
    let short = match m {
        "Neural Network (Specific Model)" => "specific (NN)".to_string(),
        "Gradient Boost (General Model)" => "general (GBM)".to_string(),
        _ => m.replace("-based", "").replace("-confidence", "").replace("lower-bound", "lower bound"),
    };
    if short == m {
        return Cell::text(m);
    }
    Cell { html: format!("<span title=\"{}\">{}</span>", html_escape(m), html_escape(&short)), sort: Some(short) }
}

fn trace_label(r: &QcRecord) -> String {
    let mut s = extra(r, "trace_confidence").unwrap_or_else(|| "–".into());
    if let Some(tr) = extra(r, "terminal_repeat") {
        s.push_str(&format!(" · {tr}"));
        if extra(r, "repeat_flag").is_some() {
            s.push_str(" (flagged)");
        }
    }
    s
}

fn chimera_cell(r: &QcRecord) -> Cell {
    if !r.warnings.is_empty() {
        let at = extra(r, "breakpoint").map(|b| format!(" near {}", format_int(&b))).unwrap_or_default();
        return Cell { html: format!("<span class=\"flag\">junction{}</span>", html_escape(&at)), sort: Some("2".into()) };
    }
    if extra(r, "assessed").as_deref() == Some("yes") {
        Cell { html: "ok".into(), sort: Some("1".into()) }
    } else {
        Cell { html: "<span class=\"na\">too short</span>".into(), sort: Some("0".into()) }
    }
}

