/// Shorten long decimal tails for display (the TSV keeps full precision).
fn display_value(v: &str) -> String {
    let decimals = v.split_once('.').map(|(_, f)| f.len()).unwrap_or(0);
    match v.parse::<f64>() {
        Ok(x) if decimals > 4 && x.is_finite() => {
            if x.abs() >= 1.0 {
                format!("{x:.2}")
            } else {
                format!("{x:.4}")
            }
        }
        _ => v.to_string(),
    }
}

