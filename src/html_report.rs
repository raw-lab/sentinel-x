fn render_cards(units: &Units, per_contig: bool) -> String {
    let n = units.names.len();
    if n > MAX_DETAIL_UNITS {
        return String::new();
    }
    let mut cards = String::new();
    for i in 0..n {
        let u = units.view(i);
        for r in u.records {
            // per-contig CHIMERA-SCAN records of a genome-level run stay in the table
            if !per_contig && !GENOME_VALIDATORS.contains(&r.validator.as_str()) {
                continue;
            }
            cards.push_str(&render_validator_card(r, if n > 1 || per_contig { Some(u.name) } else { None }));
        }
    }
    if cards.is_empty() {
        return String::new();
    }
    format!("<h2 class=\"section\">Validator details</h2>\n<div class=\"grid\">\n{cards}</div>\n")
}

fn render_validator_card(rec: &QcRecord, unit: Option<&str>) -> String {
    let (badge_class, badge_text) = quality_badge(rec.quality);
    let mut metrics = String::new();
    let mut add = |label: &str, value: String| {
        metrics.push_str(&format!(
            "<div class=\"m\"><span class=\"ml\">{}</span><span class=\"mv\">{}</span></div>\n",
            html_escape(label),
            html_escape(&value)
        ));
    };
    if let Some(c) = rec.completeness {
        add("Completeness", format!("{c:.2}%"));
    }
    if let Some(c) = rec.contamination {
        add("Contamination", format!("{c:.2}%"));
    }
    if rec.gene_count > 0 {
        add("Genes / ORFs", rec.gene_count.to_string());
    }
    if !rec.method.is_empty() {
        add("Method", rec.method.clone());
    }
    for (k, v) in &rec.extra {
        if EXTRA_ALLOW.contains(&k.as_str()) {
            // let BUSCO's long summary string wrap at its commas
            let shown = if k == "busco" { v.replace(',', ", ") } else { display_value(v) };
            add(&pretty_key(k), shown);
        }
    }
    let badge = if matches!(rec.validator.as_str(), "checkv" | "checkm2" | "busco" | "eukcc") {
        format!("<span class=\"qbadge sm {badge_class}\">{badge_text}</span>")
    } else {
        String::new()
    };
    let unit_html = unit.map(|u| format!("<div class=\"cunit\">{}</div>", html_escape(u))).unwrap_or_default();
    format!(
        "<div class=\"card\">\n<div class=\"chead\"><span class=\"cname\">{name}</span>{badge}</div>\n{unit_html}\n\
         <div class=\"metrics\">\n{metrics}</div>\n</div>\n",
        name = html_escape(&validator_title(&rec.validator)),
    )
}

