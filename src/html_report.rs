fn render_warnings(report: &QcReport, units: &Units) -> String {
    let unit_of = |r: &QcRecord| -> String {
        if units.kind == "genome" && !GENOME_VALIDATORS.contains(&r.validator.as_str()) {
            match extra(r, "genome") {
                Some(g) => format!("{g} / {}", r.contig_id),
                None => r.contig_id.clone(),
            }
        } else {
            r.contig_id.clone()
        }
    };
    let all: Vec<(&str, String, &String)> = report
        .records
        .iter()
        .flat_map(|r| r.warnings.iter().map(move |w| (r.validator.as_str(), r, w)))
        .map(|(v, r, w)| (v, unit_of(r), w))
        .collect();
    if all.is_empty() {
        return String::new();
    }
    let mut s =
        format!("<h2 class=\"section\">Warnings <span class=\"hint\">{}</span></h2>\n<div class=\"warnbox\">\n", all.len());
    for (v, unit, w) in all.iter().take(MAX_WARNINGS) {
        s.push_str(&format!(
            "<div class=\"warn\"><span class=\"wtag\">{}</span><span class=\"wunit\">{}</span>{}</div>\n",
            html_escape(&validator_title(v)),
            html_escape(unit),
            html_escape(w)
        ));
    }
    if all.len() > MAX_WARNINGS {
        s.push_str(&format!(
            "<div class=\"note\">{} more warnings are in the TSV/JSON outputs.</div>\n",
            all.len() - MAX_WARNINGS
        ));
    }
    s.push_str("</div>\n");
    s
}

