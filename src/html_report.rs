fn format_bp(s: &str) -> String {
    match s.parse::<u64>() {
        Ok(n) if n >= 1_000_000 => format!("{:.2} Mb", n as f64 / 1e6),
        Ok(n) if n >= 1_000 => format!("{:.1} kb", n as f64 / 1e3),
        Ok(n) => format!("{n} bp"),
        Err(_) => s.to_string(),
    }
}

/// `12345` → `12,345`.
fn format_int(s: &str) -> String {
    match s.parse::<u64>() {
        Ok(n) => {
            let d = n.to_string();
            let mut out = String::new();
            for (i, ch) in d.chars().enumerate() {
                if i > 0 && (d.len() - i) % 3 == 0 {
                    out.push(',');
                }
                out.push(ch);
            }
            out
        }
        Err(_) => s.to_string(),
    }
}

/// Render a 0..1 fraction as a percentage; pass through anything else.
fn format_fraction_pct(s: &str) -> String {
    match s.parse::<f64>() {
        Ok(f) if (0.0..=1.0).contains(&f) => format!("{:.1}%", f * 100.0),
        _ => s.to_string(),
    }
}

fn html_escape(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;").replace('\'', "&#39;")
}

fn current_date() -> String {
    // UTC date without pulling in chrono.
    let secs = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0);
    let (y, m, d) = civil_from_days((secs / 86_400) as i64);
    format!("{y:04}-{m:02}-{d:02}")
}

/// Howard Hinnant's days->civil date algorithm.
fn civil_from_days(z: i64) -> (i64, u32, u32) {
    let z = z + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = (z - era * 146_097) as u64;
    let yoe = (doe - doe / 1460 + doe / 36524 - doe / 146_096) / 365;
    let y = yoe as i64 + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    (if m <= 2 { y + 1 } else { y }, m, d)
}

